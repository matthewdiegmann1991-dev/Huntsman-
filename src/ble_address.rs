//! Bluetooth LE device-address typing, offline, from the address alone.
//!
//! A Bluetooth LE device address is public (an IEEE-assigned MAC, so the OUI registry names its
//! maker) or random, and a random address is typed by the two most significant bits of its most
//! significant byte, the first byte as written (Core Specification Vol. 6, Part B, 1.3): `11` a
//! static address, fixed at least until the device powers off; `01` a resolvable private address,
//! generated from the device's identity-resolving key and rotated (Android rotates about every
//! fifteen minutes), so it does not identify the device later; `00` a non-resolvable private
//! address, rotated and unlinkable; `10` reserved. The same 48 bits may be a Wi-Fi MAC, whose U/L
//! bit (bit 1 of the first byte) means something else and is set or clear at random in a random
//! Bluetooth address, so the Wi-Fi and Bluetooth readings are given side by side and neither is
//! asserted to be the one the address was captured as. Nothing here identifies a device or a
//! person: a name or a manufacturer comes from the advertisement, never from the address.

use crate::oui;

/// What a Bluetooth LE address is, by its bits.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BleAddressKind {
    /// An IEEE-registered prefix: a public device address, or a static random address that
    /// happens to share a registered prefix (the bits cannot tell those apart).
    Public,
    /// `11`: a static random address, fixed at least until the device powers off.
    StaticRandom,
    /// `01`: a resolvable private address, rotated; it does not identify the device later.
    ResolvablePrivate,
    /// `00`: a non-resolvable private address, rotated and unlinkable.
    NonResolvablePrivate,
    /// `10`: reserved by the specification; not a valid random address.
    Reserved,
}

impl BleAddressKind {
    /// The kind as an attribute value.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Public => "public",
            Self::StaticRandom => "static_random",
            Self::ResolvablePrivate => "resolvable_private",
            Self::NonResolvablePrivate => "non_resolvable_private",
            Self::Reserved => "reserved",
        }
    }

    /// What the kind says about recognising the device by this address later.
    #[must_use]
    pub const fn persistence(self) -> &'static str {
        match self {
            Self::Public => {
                "a public device address keeps its IEEE-registered prefix for the life of the device, unless it is a static random address that happens to share a registered prefix"
            }
            Self::StaticRandom => {
                "a static random address is fixed at least until the device powers off and carries no manufacturer prefix"
            }
            Self::ResolvablePrivate => {
                "a resolvable private address is generated by the device and rotated, carries no manufacturer prefix, and does not identify the device later"
            }
            Self::NonResolvablePrivate => {
                "a non-resolvable private address is rotated and unlinkable, and carries no manufacturer prefix"
            }
            Self::Reserved => {
                "the specification reserves this bit pattern; not a valid random address"
            }
        }
    }
}

/// The Bluetooth LE reading of `address`: public when the IEEE registry names its prefix
/// (`registered`), else by the two most significant bits of its first byte. `None` for a value
/// that is not six octets. **Pure.**
#[must_use]
pub fn classify(address: &str, registered: bool) -> Option<BleAddressKind> {
    let octets = oui::octets(address)?;
    if registered {
        return Some(BleAddressKind::Public);
    }
    Some(match octets[0] >> 6 {
        0b11 => BleAddressKind::StaticRandom,
        0b01 => BleAddressKind::ResolvablePrivate,
        0b00 => BleAddressKind::NonResolvablePrivate,
        _ => BleAddressKind::Reserved,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_random_address_is_typed_by_its_top_two_bits_whatever_the_ul_bit_says() {
        // 0x67 = 0110 0111: `01`, resolvable private, with the Wi-Fi U/L bit set by chance.
        assert_eq!(
            classify("67:06:21:95:C1:7C", false),
            Some(BleAddressKind::ResolvablePrivate)
        );
        // 0x64 = 0110 0100: the same kind with the U/L bit clear.
        assert_eq!(
            classify("64-06-21-95-C1-7C", false),
            Some(BleAddressKind::ResolvablePrivate)
        );
        // 0xD6 = 1101 0110: `11`, static.
        assert_eq!(
            classify("D6:92:5E:AF:76:C9", false),
            Some(BleAddressKind::StaticRandom)
        );
        // 0x3A = 0011 1010: `00`, non-resolvable.
        assert_eq!(
            classify("3a:92:5e:af:76:c9", false),
            Some(BleAddressKind::NonResolvablePrivate)
        );
        // 0x9A = 1001 1010: `10`, reserved.
        assert_eq!(
            classify("9A92.5EAF.76C9", false),
            Some(BleAddressKind::Reserved)
        );
        assert_eq!(classify("D6:92:5E:AF:76", false), None);
        assert_eq!(classify("not an address", true), None);
    }

    #[test]
    fn a_registered_prefix_reads_as_public_and_every_kind_explains_itself() {
        assert_eq!(
            classify("D6:92:5E:AF:76:C9", true),
            Some(BleAddressKind::Public)
        );
        let kinds = [
            BleAddressKind::Public,
            BleAddressKind::StaticRandom,
            BleAddressKind::ResolvablePrivate,
            BleAddressKind::NonResolvablePrivate,
            BleAddressKind::Reserved,
        ];
        let names: std::collections::BTreeSet<&str> = kinds.iter().map(|k| k.name()).collect();
        assert_eq!(names.len(), kinds.len());
        for kind in kinds {
            assert!(kind.persistence().len() > 40, "{}", kind.name());
        }
        assert!(
            BleAddressKind::ResolvablePrivate
                .persistence()
                .contains("does not identify the device later")
        );
    }
}
